def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    OUT.mkdir(parents=True, exist_ok=True)

    with open(OUT / "anketa-batkiv.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["id", "клас", "відповідь"])
        for i, (grade, text, _) in enumerate(ROWS, start=1):
            w.writerow([i, grade, text])

    with open(OUT / "anketa-temy-shi.csv", "w", newline="", encoding="utf-8-sig") as f:
        w = csv.writer(f)
        w.writerow(["id", "тема"])
        for i, (_, _, themes) in enumerate(ROWS, start=1):
            for code in themes.split(";"):
                w.writerow([i, THEMES[code]])

    counts = Counter(code for _, _, t in ROWS for code in t.split(";"))
    n = len(ROWS)
    print(f"Відповідей: {n}")
    for code, k in counts.most_common():
        ids = [str(i) for i, (_, _, t) in enumerate(ROWS, start=1) if code in t.split(";")]
        print(f"{k:3d}  {k / n:5.1%}  {THEMES[code]}  [{', '.join(ids)}]")


if __name__ == "__main__":
    main()
